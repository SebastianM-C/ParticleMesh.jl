#!/usr/bin/env python3
"""Smilei v5.1 namelists of the WP-064/065 ionization-injection LWFA case (ParticleMesh's
scripts/optim/born2d_case.jl and trapped2d_case.jl at a0 = 1.9) with a choice of Maxwell solver.

    python3 gen.py <outdir> --ppl 32 --ny 2 --solver Yee|Lehe|M4 [--dt yee|magic] [--vacuum]
                   [--a0scale 1.0] [--ionppc 16x16] [--seed 0] [--threads 4]

Units: Smilei normalized with omega_0 as reference (A1). Box and plasma as ParticleMesh's case
(box coordinates, box back at x = 0 at t = 0). The laser follows scripts/lwfa/lwfa.jl's
smilei_laser (ghost-node offset, carrier phase with Gouy phase, narrower waist for the
Silver-Muller response); the launch amplitude is set by the vacuum energy calibration instead of
the analytic launch factor (a0scale). Differences from ParticleMesh that are kept on purpose and
are the same for every solver: Smilei's envelope runs along the wavefront (ParticleMesh's AxisTime
does not), ionization is Monte Carlo ADK ("tunnel") with the ionization current, and the
transverse edges are Silver-Muller (ParticleMesh: PML).
"""
import argparse, json, math, os

CASE = dict(waist=10.0, delay=54.0, focus=80.0, vacuum=64.0, ramp=40.0, start=108.0, a0=1.9, duration=6.0,
            density=0.072, length_wavelengths=14, rows=128, ppc=(2, 2), t_end=300.0, dopant_fraction=0.01,
            section=(108.0, 132.0, 4.0), half_rows=18, wavelength=0.8e-6, antenna_x=12 * 2 * math.pi / 32)
GHOST = 2

def derived(ppl, ny, solver, dtmode):
    dx = 2 * math.pi / ppl
    dy = math.pi / 4 / ny
    nx, nyc = CASE["length_wavelengths"] * ppl, CASE["rows"] * ny
    dt_yee = 0.95 / math.sqrt(1 / dx**2 + 1 / dy**2)
    if dtmode == "yee":
        dt = dt_yee
    elif dtmode == "magic":
        dt = dx  # Lehe and M4 are free of dispersion along x at c dt = dx
    else:
        dt = float(dtmode) * dx
    nsteps = math.ceil(CASE["t_end"] / dt)
    return dict(dx=dx, dy=dy, nx=nx, ny=nyc, dt=dt, dt_yee=dt_yee, nsteps=nsteps, yc=nyc * dy / 2)

def smilei_laser(d, a0scale):
    """As scripts/lwfa/lwfa.jl smilei_laser, with the case's antenna plane x_a = 2.356 (box
    coordinates): the axis peak crosses x = 0 at delay - x_a and the focus is 80 from x = 0."""
    back = GHOST * d["dx"]
    focus = CASE["focus"] + back
    w0 = CASE["waist"]
    waist = math.sqrt(w0**2 - 1)
    zR = waist**2 / 2
    c0 = math.pi / 2 - math.atan(focus / zR) / 2
    delay = CASE["delay"] - CASE["antenna_x"]
    center = c0 + 2 * math.pi * math.ceil((delay - c0) / (2 * math.pi))
    return dict(a0=CASE["a0"] * a0scale * w0 / waist, waist=waist, focus=focus, center=center, duration=2 * center,
                fwhm=2 * CASE["duration"] * math.sqrt(math.log(2)), phase_offset=center - (delay - back))

def namelist(ppl, ny, solver, dtmode, vacuum, a0scale, ionppc, seed, probe_every_t=2.5, t_end=None):
    d = derived(ppl, ny, solver, dtmode)
    if t_end is not None:
        d["nsteps"] = math.ceil(t_end / d["dt"])
    las = smilei_laser(d, a0scale)
    n = d["nsteps"]
    pe = max(1, round(probe_every_t / d["dt"]))
    cal = round(100.0 / d["dt"])
    x0, x1, xr = CASE["section"]
    yc = d["yc"]
    rows = CASE["half_rows"] * ny * d["dy"]
    s = f'''# Smilei namelist generated by gen.py: ppl={ppl} ny={ny} solver={solver} dt={dtmode} vacuum={vacuum}
# a0scale={a0scale!r} ionppc={ionppc} seed={seed}. Units: omega_0 reference (A1).
import math
import numpy as np

Main(
    geometry = "2Dcartesian",
    interpolation_order = 2,
    maxwell_solver = "{solver}",
    cell_length = [{d["dx"]!r}, {d["dy"]!r}],
    number_of_cells = [{d["nx"]}, {d["ny"]}],
    timestep = {d["dt"]!r},
    simulation_time = {(n + 0.5) * d["dt"]!r},
    number_of_patches = [32, 4],
    EM_boundary_conditions = [["silver-muller"], ["silver-muller"]],
    solve_poisson = False,
    reference_angular_frequency_SI = {2 * math.pi * 299792458.0 / CASE["wavelength"]!r},
    random_seed = {seed},
    print_every = 500,
)

MovingWindow(time_start = {CASE["start"]!r}, velocity_x = 1.0)

LaserGaussian2D(
    box_side = "xmin",
    a0 = {las["a0"]!r},
    omega = 1.0,
    focus = [{las["focus"]!r}, {yc!r}],
    waist = {las["waist"]!r},
    polarization_phi = 0.0,
    time_envelope = tgaussian(start = 0.0, duration = {las["duration"]!r}, fwhm = {las["fwhm"]!r}, center = {las["center"]!r}),
    phase_offset = {las["phase_offset"]!r},
)

DiagScalar(every = {pe}, precision = 12)

DiagProbe(
    every = {pe},
    origin = [0.0, {yc!r}],
    corners = [[{d["nx"] * d["dx"]!r}, {yc!r}]],
    number = [{4 * d["nx"]}],
    fields = ["Ex", "Ey", "Bz", "Rho"],
)

DiagFields(every = [{cal}, {cal}, 1], fields = ["Ex", "Ey", "Bz_m"], datatype = "double")
'''
    if not vacuum:
        ix, iy = ionppc
        s += f'''
def plasma_density(x, y):
    s = np.clip((x - {CASE["vacuum"]!r}) / {CASE["ramp"]!r}, 0.0, 1.0)
    return {CASE["density"]!r} * np.sin(0.5 * math.pi * s)**2

def rise(s):
    return np.sin(0.5 * math.pi * np.clip(s / {xr!r}, 0.0, 1.0))**2

def dopant_density(x, y):
    sec = rise(x - {x0!r}) * (1.0 - rise(x - {x1!r}))
    return {CASE["dopant_fraction"] * CASE["density"]!r} * plasma_density(x, y) / {CASE["density"]!r} * sec * (np.abs(y - {yc!r}) < {rows!r})

Species(
    name = "electron",
    position_initialization = "regular",
    regular_number = [2, 2],
    momentum_initialization = "cold",
    particles_per_cell = 4,
    mass = 1.0, charge = -1.0,
    number_density = plasma_density,
    boundary_conditions = [["remove", "remove"], ["remove", "remove"]],
)

Species(
    name = "born",
    position_initialization = "regular",
    momentum_initialization = "cold",
    particles_per_cell = 0,
    mass = 1.0, charge = -1.0,
    number_density = 0.0,
    boundary_conditions = [["remove", "remove"], ["remove", "remove"]],
)

Species(
    name = "nitrogen",
    position_initialization = "regular",
    regular_number = [{ix}, {iy}],
    momentum_initialization = "cold",
    particles_per_cell = {ix * iy},
    atomic_number = 7,
    charge = 5.0,
    mass = {14 * 1836.15267343!r},
    number_density = dopant_density,
    time_frozen = 1.0e9,
    ionization_model = "tunnel",
    ionization_electrons = "born",
    boundary_conditions = [["remove", "remove"], ["remove", "remove"]],
)

DiagTrackParticles(species = "born", every = [{n}, {n}, 1], attributes = ["x", "y", "px", "py", "pz", "w"])

def fast(particles):
    return particles.px > 1.5

DiagTrackParticles(species = "electron", every = [{n}, {n}, 1], filter = fast, attributes = ["x", "y", "px", "py", "pz", "w"])

DiagParticleBinning(deposited_quantity = "weight", every = [{n}, {n}, 1], species = ["born"],
                    axes = [["moving_x", 0.0, {d["nx"] * d["dx"]!r}, {d["nx"] // 4}]])
'''
    meta = dict(ppl=ppl, nyfac=ny, solver=solver, dtmode=dtmode, vacuum=vacuum, a0scale=a0scale, ionppc=list(ionppc),
                seed=seed, probe_every=pe, cal_step=cal, laser=las, **d)
    return s, meta

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--ppl", type=int, default=32)
    ap.add_argument("--ny", type=int, default=2)
    ap.add_argument("--solver", default="Yee")
    ap.add_argument("--dt", default="yee")
    ap.add_argument("--vacuum", action="store_true")
    ap.add_argument("--a0scale", type=float, default=1.0)
    ap.add_argument("--ionppc", default="16x16")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--tend", type=float, default=None)
    a = ap.parse_args()
    ionppc = tuple(int(v) for v in a.ionppc.split("x"))
    s, meta = namelist(a.ppl, a.ny, a.solver, a.dt, a.vacuum, a.a0scale, ionppc, a.seed, t_end=a.tend)
    os.makedirs(a.outdir, exist_ok=True)
    open(os.path.join(a.outdir, "namelist.py"), "w").write(s)
    json.dump(meta, open(os.path.join(a.outdir, "meta.json"), "w"), indent=1)
    print(a.outdir, "steps", meta["nsteps"], "dt", meta["dt"])
